export type PublicFilm = {
  id: string;
  koTitle: string;
  originalTitle: string;
  year: number;
  type: FilmType;
  periodStart: number;
  periodEnd: number;
  lanes: LaneId[];
  netflixKr?: true;
  checkedAt?: typeof NETFLIX_CHECKED_AT;
};

export function toCatalog(list: Film[] = films): PublicFilm[] {
  return [...list]
    .sort((a, b) => a.periodStart - b.periodStart || a.periodEnd - b.periodEnd || a.id.localeCompare(b.id))
    .map((film) => {
      const row: PublicFilm = {
        id: film.id,
        koTitle: film.koTitle,
        originalTitle: film.originalTitle,
        year: film.year,
        type: film.type,
        periodStart: film.periodStart,
        periodEnd: film.periodEnd,
        lanes: film.lanes,
      };
      if (film.netflixKr) {
        row.netflixKr = true;
        row.checkedAt = film.checkedAt;
      }
      return row;
    });
}

const filmsByEvent = new Map<string, Film[]>();
for (const film of films) {
  for (const slug of film.eventIds) {
    const bucket = filmsByEvent.get(slug);
    if (bucket) bucket.push(film);
    else filmsByEvent.set(slug, [film]);
  }
}
for (const bucket of filmsByEvent.values()) {
  bucket.sort((a, b) => a.year - b.year || a.id.localeCompare(b.id));
}

export function filmsForEvent(slug: string) {
  return filmsByEvent.get(slug) ?? [];
}

export function chronologicalFilms() {
  return [...films].sort((a, b) => a.periodStart - b.periodStart || a.periodEnd - b.periodEnd || a.id.localeCompare(b.id));
}
